from fastapi import APIRouter, HTTPException, BackgroundTasks
from pydantic import BaseModel, Field

# Add parent directory to path for imports
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from shared_utils import get_db_connection

router = APIRouter()


# =============================================================================
# Models
# =============================================================================

class PromptType(str, Enum):
    WET_SIGNATURE = "wet_signature_detection"
    RED_FLAGS = "red_flags_analysis"
    DEFINITION = "definition_extraction"


class OptimizerType(str, Enum):
    BOOTSTRAP_FEWSHOT = "bootstrap_fewshot"
    COPRO = "copro"
    AUTO = "auto"  # Automatically select based on data size


class OptimizationRequest(BaseModel):
    """Request to start an optimization job."""
    prompt_type: PromptType
    max_iterations: int = Field(default=10, ge=1, le=50)
    num_candidates: int = Field(default=3, ge=1, le=10)
    teacher_model: str = Field(default="anthropic/claude-3-5-haiku-20241022")
    optimizer: OptimizerType = Field(default=OptimizerType.AUTO)


class OptimizationStatus(str, Enum):
    PENDING = "pending"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"


class CandidatePrompt(BaseModel):
    """A candidate prompt generated by optimization."""
    id: str
    system_prompt: str
    template: str
    score: float
    metrics: dict


class OptimizationJob(BaseModel):
    """Status and results of an optimization job."""
    job_id: str
    prompt_type: PromptType
    status: OptimizationStatus
    created_at: datetime
    updated_at: datetime
    progress: int = Field(default=0, ge=0, le=100)
    current_iteration: int = 0
    max_iterations: int
    best_score: Optional[float] = None
    candidates: list[CandidatePrompt] = []
    error: Optional[str] = None
    cost_estimate: Optional[float] = None
    actual_cost: Optional[float] = None


class CostEstimate(BaseModel):
    """Estimated cost for an optimization run."""
    estimated_tokens: int
    estimated_cost_usd: float
    model: str
    num_examples: int
    iterations: int


# =============================================================================
# In-memory job storage (for MVP - would use database in production)
# =============================================================================

_jobs: dict[str, OptimizationJob] = {}


