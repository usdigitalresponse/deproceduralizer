def get_data_readiness(prompt_type: str) -> dict:
    """Get data readiness stats for a prompt type."""
    conn = get_db_connection()
    if not conn:
        return {
            "reviewed_count": 0,
            "minimum_threshold": 10,
            "recommended_threshold": 50,
            "error": "Database connection failed"
        }

    try:
        with conn.cursor() as cur:
            if prompt_type == "wet_signature_detection":
                cur.execute("""
                    SELECT COUNT(*) FROM compliance_issues
                    WHERE review_status IN ('confirmed', 'false_positive')
                    AND issue_type = 'wet_signature'
                """)
            elif prompt_type == "red_flags_analysis":
                cur.execute("""
                    SELECT COUNT(*) FROM red_flags
                    WHERE review_status IN ('confirmed', 'false_positive', 'corrected')
                """)
            elif prompt_type == "definition_extraction":
                cur.execute("""
                    SELECT COUNT(*) FROM definitions
                    WHERE review_status IN ('confirmed', 'false_positive', 'corrected')
                """)
            else:
                return {"error": f"Unknown prompt type: {prompt_type}"}

            count = cur.fetchone()[0]

        return {
            "reviewed_count": count,
            "minimum_threshold": 10,  # BootstrapFewShot minimum
            "recommended_threshold": 50,  # COPRO recommended
            "optimal_threshold": 200,  # MIPROv2 optimal
        }
    except Exception as e:
        return {"error": str(e), "reviewed_count": 0}
    finally:
        conn.close()


def estimate_cost(
    prompt_type: str,
    model: str,
    iterations: int,
    num_examples: int
) -> float:
    """Estimate cost in USD for an optimization run."""
    tokens_per_example = 2000
    total_tokens = tokens_per_example * num_examples * iterations

    # Cost per 1M tokens
    if "haiku" in model:
        cost_per_million = 0.25
    elif "sonnet" in model:
        cost_per_million = 3.0
    else:
        cost_per_million = 15.0  # Opus

    return round((total_tokens / 1_000_000) * cost_per_million, 4)


async def run_optimization_job(job_id: str, request: OptimizationRequest):
    """
    Background task to run the optimization.

    This is where the actual DSPy optimization happens.
    """
    job = _jobs[job_id]
    job.status = OptimizationStatus.RUNNING
    job.updated_at = datetime.utcnow()

    try:
        # Fetch training data
        trainset = await fetch_training_data(request.prompt_type.value)

        if not trainset:
            raise ValueError("No training data available")

        # Import DSPy modules
        from scripts.optimize_prompts import (
            optimize_wet_signature_prompt,
            optimize_red_flags_prompt,
            optimize_definition_prompt,
            export_optimized_prompt
        )

        # Run optimization based on prompt type
        if request.prompt_type == PromptType.WET_SIGNATURE:
            optimized, history = optimize_wet_signature_prompt(
                trainset=trainset,
                num_candidates=request.num_candidates,
                max_iterations=request.max_iterations,
                teacher_model=request.teacher_model
            )
        elif request.prompt_type == PromptType.RED_FLAGS:
            optimized, history = optimize_red_flags_prompt(
                trainset=trainset,
                num_candidates=request.num_candidates,
                max_iterations=request.max_iterations,
                teacher_model=request.teacher_model
            )
        elif request.prompt_type == PromptType.DEFINITION:
            optimized, history = optimize_definition_prompt(
                trainset=trainset,
                num_candidates=request.num_candidates,
                max_iterations=request.max_iterations,
                teacher_model=request.teacher_model
            )

        # Export optimized prompt
        exported = export_optimized_prompt(optimized, request.prompt_type.value)

        # Create candidate from result
        candidate = CandidatePrompt(
            id=str(uuid4()),
            system_prompt=exported.get("system", ""),
            template=exported.get("template", ""),
            score=0.0,  # Would come from optimization history
            metrics=history
        )

        job.candidates = [candidate]
        job.best_score = candidate.score
        job.progress = 100
        job.status = OptimizationStatus.COMPLETED

    except Exception as e:
        job.status = OptimizationStatus.FAILED
        job.error = str(e)
        import traceback
        print(f"Optimization failed: {traceback.format_exc()}")

    job.updated_at = datetime.utcnow()


async def fetch_training_data(prompt_type: str) -> list:
    """
    Fetch reviewed training data from the database.

    Returns list of example objects suitable for DSPy optimization.
    """
    conn = get_db_connection()
    if not conn:
        return []

    try:
        with conn.cursor() as cur:
            if prompt_type == "wet_signature_detection":
                cur.execute("""
                    SELECT
                        ci.id,
                        ci.review_status,
                        ci.section_text,
                        rd.citation,
                        rd.heading
                    FROM compliance_issues ci
                    JOIN regulatory_documents rd ON ci.document_id = rd.id
                    WHERE ci.review_status IN ('confirmed', 'false_positive')
                    AND ci.issue_type = 'wet_signature'
                """)

                from scripts.optimize_prompts import WetSignatureExample
                rows = cur.fetchall()
                return [
                    WetSignatureExample(
                        section_text=row[2] or "",
                        citation=row[3] or "",
                        heading=row[4] or "",
                        review_status=row[1],
                        has_wet_signature_requirement=(row[1] == 'confirmed')
                    )
                    for row in rows
                ]

            elif prompt_type == "red_flags_analysis":
                cur.execute("""
                    SELECT
                        rf.id,
                        rf.review_status,
                        rf.category,
                        rf.severity,
                        rf.section_text,
                        rd.citation,
                        rd.heading
                    FROM red_flags rf
                    JOIN regulatory_documents rd ON rf.document_id = rd.id
                    WHERE rf.review_status IN ('confirmed', 'false_positive', 'corrected')
                """)

                from scripts.optimize_prompts import RedFlagExample
                rows = cur.fetchall()
                return [
                    RedFlagExample(
                        section_text=row[4] or "",
                        citation=row[5] or "",
                        heading=row[6] or "",
                        review_status=row[1],
                        category=row[2] or "",
                        severity=row[3] or 5,
                        has_implementation_issues=(row[1] != 'false_positive')
                    )
                    for row in rows
                ]

            elif prompt_type == "definition_extraction":
                cur.execute("""
                    SELECT
                        d.id,
                        d.review_status,
                        d.term,
                        d.verbatim_text,
                        d.is_verbatim,
                        d.definition_type,
                        d.section_text,
                        rd.citation,
                        rd.heading
                    FROM definitions d
                    JOIN regulatory_documents rd ON d.document_id = rd.id
                    WHERE d.review_status IN ('confirmed', 'false_positive', 'corrected')
                """)

                from scripts.optimize_prompts import DefinitionExample
                rows = cur.fetchall()
                return [
                    DefinitionExample(
                        section_text=row[6] or "",
                        citation=row[7] or "",
                        heading=row[8] or "",
                        review_status=row[1],
                        term=row[2] or "",
                        verbatim_text=row[3] or "",
                        is_verbatim=row[4] or False,
                        definition_type=row[5] or "formal"
                    )
                    for row in rows
                ]

        return []
    except Exception as e:
        print(f"Error fetching training data: {e}")
        return []
    finally:
        conn.close()
