@router.post("/start", response_model=OptimizationJob)
async def start_optimization(
    request: OptimizationRequest,
    background_tasks: BackgroundTasks
) -> OptimizationJob:
    """
    Start a new optimization job.

    The optimization runs in the background. Use GET /status/{job_id} to check progress.
    """
    # Check data readiness
    readiness = get_data_readiness(request.prompt_type.value)
    if readiness["reviewed_count"] < readiness["minimum_threshold"]:
        raise HTTPException(
            status_code=400,
            detail=f"Not enough reviewed data. Have {readiness['reviewed_count']}, need {readiness['minimum_threshold']}. "
                   f"Review more items before running optimization."
        )

    # Create job
    job_id = str(uuid4())
    now = datetime.utcnow()

    job = OptimizationJob(
        job_id=job_id,
        prompt_type=request.prompt_type,
        status=OptimizationStatus.PENDING,
        created_at=now,
        updated_at=now,
        max_iterations=request.max_iterations,
        cost_estimate=estimate_cost(
            request.prompt_type.value,
            request.teacher_model,
            request.max_iterations,
            readiness["reviewed_count"]
        )
    )

    _jobs[job_id] = job

    # Start background task
    background_tasks.add_task(
        run_optimization_job,
        job_id,
        request
    )

    return job


@router.get("/status/{job_id}", response_model=OptimizationJob)
async def get_job_status(job_id: str) -> OptimizationJob:
    """Get the status of an optimization job."""
    if job_id not in _jobs:
        raise HTTPException(status_code=404, detail="Job not found")
    return _jobs[job_id]


@router.get("/jobs", response_model=list[OptimizationJob])
async def list_jobs(
    prompt_type: Optional[PromptType] = None,
    status: Optional[OptimizationStatus] = None
) -> list[OptimizationJob]:
    """List all optimization jobs, optionally filtered."""
    jobs = list(_jobs.values())

    if prompt_type:
        jobs = [j for j in jobs if j.prompt_type == prompt_type]
    if status:
        jobs = [j for j in jobs if j.status == status]

    return sorted(jobs, key=lambda j: j.created_at, reverse=True)


@router.post("/estimate", response_model=CostEstimate)
async def estimate_optimization_cost(request: OptimizationRequest) -> CostEstimate:
    """
    Estimate the cost of running an optimization job.

    Does not start the job, just calculates estimated token usage and cost.
    """
    readiness = get_data_readiness(request.prompt_type.value)

    # Estimate tokens per example (roughly)
    tokens_per_example = 2000  # Input + output tokens
    total_examples = readiness["reviewed_count"]
    iterations = request.max_iterations

    # Each iteration processes all examples
    total_tokens = tokens_per_example * total_examples * iterations

    # Cost per 1M tokens (approximate for Claude 3.5 Haiku)
    cost_per_million = 0.25 if "haiku" in request.teacher_model else 3.0

    estimated_cost = (total_tokens / 1_000_000) * cost_per_million

    return CostEstimate(
        estimated_tokens=total_tokens,
        estimated_cost_usd=round(estimated_cost, 4),
        model=request.teacher_model,
        num_examples=total_examples,
        iterations=iterations
    )


@router.post("/cancel/{job_id}")
async def cancel_job(job_id: str):
    """Cancel a running optimization job."""
    if job_id not in _jobs:
        raise HTTPException(status_code=404, detail="Job not found")

    job = _jobs[job_id]
    if job.status == OptimizationStatus.RUNNING:
        job.status = OptimizationStatus.FAILED
        job.error = "Cancelled by user"
        job.updated_at = datetime.utcnow()

    return {"status": "cancelled"}


@router.post("/apply/{job_id}/{candidate_id}")
async def apply_candidate(job_id: str, candidate_id: str):
    """
    Apply a candidate prompt as the new default.

    This would update prompts.yaml with the optimized prompt.
    """
    if job_id not in _jobs:
        raise HTTPException(status_code=404, detail="Job not found")

    job = _jobs[job_id]
    candidate = next((c for c in job.candidates if c.id == candidate_id), None)

    if not candidate:
        raise HTTPException(status_code=404, detail="Candidate not found")

    # TODO: Implement actual prompts.yaml update
    # For now, just return the candidate that would be applied
    return {
        "status": "would_apply",
        "prompt_type": job.prompt_type.value,
        "candidate": candidate,
        "note": "prompts.yaml update not yet implemented"
    }


