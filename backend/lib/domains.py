# Guidance agency domains
AGENCY_DOMAINS = {
    "OCFS": "Child & Family Services",
    "NYC_DOHMH": "NYC Health",
    "NYSED": "Education",
    "JUSTICE_CENTER": "Justice Center",
    "NYSDOH": "Health",
    "NYDFS": "Financial Services",
    "DOCCS": "Corrections",
}


def domain_from_citation(citation: str) -> str:
    """
    Derive regulatory domain from a citation string.

    Examples:
        domain_from_citation("18 NYCRR 414.3") -> "Childcare"
        domain_from_citation("10 NYCRR 405.9") -> "Hospital & Nursing Facility"
        domain_from_citation("8 NYCRR 80-1.5") -> "Teacher Certification"
        domain_from_citation("18 NYCRR 352.1") -> "Public Assistance & SNAP"

    Falls back to title-level domain if no part match.
    """
    if not citation:
        return "Unknown"

    # Parse "NN NYCRR PPP.SS" or "NN NYCRR PPP-N.SS"
    m = re.match(r"(\d+)\s+NYCRR\s+(\d+(?:-\d+)?)", citation)
    if not m:
        return "Unknown"

    title = int(m.group(1))
    part_str = m.group(2)  # e.g., "418", "418-1"
    part_num = int(part_str.split("-")[0])

    # Title 18: use content-derived part lookup
    if title == 18 and part_str in TITLE_18_PART_DOMAINS:
        return TITLE_18_PART_DOMAINS[part_str]

    # Other titles: use range-based lookup
    if title in PART_DOMAINS:
        for part_range, domain in PART_DOMAINS[title]:
            if part_num in part_range:
                return domain

    # Fall back to title-level
    return TITLE_DOMAINS.get(title, "Unknown")


def domain_from_agency(agency: str, content: str | None = None) -> str:
    """Derive domain from a guidance document agency name and optional content."""
    if not agency:
        return "Unknown"

    # For OCFS, sub-classify by content keywords
    if "OCFS" in agency.upper() and content:
        cl = content.lower()
        is_cc = any(w in cl for w in ["child care", "childcare", "day care", "daycare", "school-age", "ccdf"])
        is_fc = any(w in cl for w in ["foster", "adoption", "permanency", "freed child"])
        is_pa = any(w in cl for w in ["snap", "public assistance", "tanf", "food stamp"])
        is_jj = any(w in cl for w in ["juvenile", "detention", "delinquen"])
        is_cps = any(w in cl for w in ["abuse", "neglect", "maltreatment", "mandated reporter"])

        if is_cc and not is_fc:
            return "Childcare"
        if is_fc and not is_cc:
            return "Child Welfare & Foster Care"
        if is_cc and is_fc:
            return "Childcare & Foster Care"
        if is_pa:
            return "Public Assistance & SNAP"
        if is_jj:
            return "Juvenile Justice"
        if is_cps:
            return "Child Protective Services"
        return "Child & Family Services"

    for key, domain in AGENCY_DOMAINS.items():
        if key.lower() in agency.lower():
            return domain
    return agency


def domain_from_citation_or_agency(
    citation: str | None = None,
    agency: str | None = None,
    doc_title: str | None = None,
    content: str | None = None,
) -> str:
    """
    Best-effort domain derivation from whatever info is available.
    Tries citation first, then agency, then doc_title patterns.
    """
    if citation:
        d = domain_from_citation(citation)
        if d != "Unknown":
            return d

    if agency:
        return domain_from_agency(agency, content=content)

    # Try to extract from guidance doc titles
    if doc_title:
        title_lower = doc_title.lower()
        if "ocfs" in title_lower:
            return "Child & Family Services"
        if "doh" in title_lower or "health" in title_lower:
            return "Health"

    return "Unknown"
